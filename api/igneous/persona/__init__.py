"""A synthetic persona: one fictional person's two years, in the export formats the real importers read.

Mira Castellanos studies computer science at Lakeshore University (a fictional school in a fictional lakeside city,
Port Avalon) from August 2024 to her graduation in May 2026, works part-time and then full-time at Northwind
Robotics, travels to Lisbon (spring break 2025) and Iceland (June 2026), and builds Tidepool, an open-source beach
water-quality app, with a friend. Her mailbox, Google Takeout, LinkedIn and ChatGPT exports and her documents folder
carry the shapes the derived stages look for: classes named by course code over a semester, trips that burst
across mail, chat, tasks and documents, a job with colleagues in mail and chat, a repository-style project folder,
introductions, promises that later mail confirms, and people who write from two addresses.

Everything is invented and generated deterministically from a seed, with no network and no model calls: the same
seed writes the same bytes. `generate` writes the exports and a manifest; `load.py` imports them through the
Sources registry (`igneous sync persona`) into a database of their own. The gold set beside this module
(gold/) names the persona's threads, the identities that are one person, and Ask questions, by stable record keys.
"""
import hashlib
import json
import shutil
from datetime import date
from pathlib import Path

from igneous.persona import everyday, formats, profile, project, routine, school, trips, work
from igneous.persona.cast import EXPORTED, FIRST_DAY, LAST_DAY, ME
from igneous.persona.life import Life

DEFAULT_SEED = 222
MANIFEST = "manifest.json"
NOTICE = ("SYNTHETIC PERSONA: invented for Igneous demos and evaluation. Every person, organization, address and "
          "record is fictional.")
GOLD = Path(__file__).with_name("gold")


def life(seed: int = DEFAULT_SEED, until: date | None = None) -> Life:
    """Every record of the persona, before any file is written (up to `until`, when given)."""
    lf = Life(seed)
    for storyline in (school, work, trips, project, everyday, routine):
        storyline.write(lf)
    profile.resumes(lf)
    if until is not None:
        lf.cut(until)
    return lf


def _readme(manifest: dict) -> str:
    c = manifest["counts"]
    e = manifest["exports"]
    return f"""# Synthetic persona: {ME.name}

{NOTICE}

Generated by `igneous persona generate` (seed {manifest['seed']}), covering {manifest['first_day']} to
{manifest['last_day']}. Import it with `igneous sync persona --path <this folder>` into a database of its own
(`make persona` does everything: generate, create igneous_persona, import, build the graph).

| Export | Read by | Contents |
|---|---|---|
| `{e['maildir']}/{e['mailbox']}` | Enron demo mailbox connector (email) | {c['mail']} messages |
| `{e['takeout']}` | Google Takeout | {c['chat_lines']} chat messages in {c['chat_spaces']} conversations, {c['tasks']} tasks, {c['meetings']} Meet calls, {c['place_visits']} place visits, {c['activity']} My Activity entries and {c['gemini_prompts']} Gemini prompts, {c['page_visits']} Chrome visits, {c['calendar_events']} calendar events (repeating classes and meetings among them) |
| `{e['linkedin']}` | LinkedIn | profile, positions, education, projects, {c['linkedin_connections']} connections |
| `{e['chatgpt']}` | ChatGPT export | {c['chatgpt_conversations']} conversations |
| `{e['documents']}` | Local files | {c['documents']} files, including a git checkout |
"""


def generate(out: Path, seed: int = DEFAULT_SEED, until: date | None = None) -> dict:
    """Write the persona's exports to `out` and return its manifest: what was written, counts, the keys of the
    records the gold set names (by tag), and a hash of every file. A persona already in `out` is replaced whole (a
    file left from another seed would be imported too); any other non-empty folder is refused."""
    out = Path(out)
    if out.is_dir() and any(out.iterdir()):
        previous = out / MANIFEST
        if not previous.is_file() or json.loads(previous.read_text()).get("name") != "igneous-persona":
            raise ValueError(f"{out} is not empty and holds no persona: choose an empty or new folder.")
        shutil.rmtree(out)
    lf = life(seed, until)
    keys: dict[str, dict] = {}
    keys |= formats.write_maildir(lf, out / "maildir")
    keys |= formats.write_takeout(lf, out / formats.TAKEOUT)
    connections = formats.write_linkedin(lf, out / formats.LINKEDIN, until)
    keys |= formats.write_chatgpt(lf, out / formats.CHATGPT)
    keys |= formats.write_documents(lf, out / formats.DOCUMENTS)
    manifest = {
        "format": 1, "name": "igneous-persona", "synthetic": True, "notice": NOTICE, "seed": seed,
        "person": ME.name, "first_day": FIRST_DAY.isoformat(), "last_day": (until or LAST_DAY).isoformat(),
        "exported": EXPORTED.isoformat(),
        "exports": {"maildir": "maildir", "mailbox": formats.MAILBOX, "takeout": formats.TAKEOUT,
                    "linkedin": formats.LINKEDIN, "chatgpt": formats.CHATGPT, "documents": formats.DOCUMENTS},
        "counts": {"mail": len(lf.mails), "chat_lines": len(lf.lines), "chat_spaces": len(lf.spaces),
                   "chatgpt_conversations": len(lf.conversations), "documents": len(lf.docs),
                   "task_lists": len(lf.task_lists), "tasks": sum(len(t.tasks) for t in lf.task_lists),
                   "place_visits": len(lf.visits), "activity": len(lf.searches), "gemini_prompts": len(lf.prompts),
                   "page_visits": len(lf.pages), "meetings": len(lf.meetings), "calendar_events": len(lf.events),
                   "linkedin_connections": connections},
        "keys": dict(sorted(keys.items())),
    }
    formats.write_file(out / "README.md", _readme(manifest).encode(), EXPORTED)
    manifest["files"] = {p.relative_to(out).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
                         for p in sorted(out.rglob("*")) if p.is_file() and p.name != MANIFEST}
    formats.write_file(out / MANIFEST, (json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode(), EXPORTED)
    return manifest


def load_gold(name: str):
    """A gold file beside the generator: threads.json and people.json (JSON), questions.jsonl (one per line)."""
    path = GOLD / name
    if path.suffix == ".jsonl":
        return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
    return json.loads(path.read_text())
